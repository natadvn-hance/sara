const NAMES = new Set(`${FEMALE} ${MALE}`.split(/\s+/).filter((n) => /^[а-я]+$/.test(n)))

const fold = (s: string) => s.toLowerCase().replace(/ё/g, 'е')
const capital = (s: string) => `${s.charAt(0).toUpperCase()}${s.slice(1)}`

/** The formal Russian first name a word stands for, capitalized; null when the word is no name Sara knows. */
export function formalName(word: string): string | null {
  const w = fold(word.trim())
  if (/^[a-z]+$/.test(w)) {
    const ru = LATIN[w]
    return ru ? capital(ru) : null
  }
  const formal = FORMAL[w] ?? w
  return NAMES.has(formal) ? capital(formal) : null
}
